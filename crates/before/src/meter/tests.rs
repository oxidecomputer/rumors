/// The freeze-parade block's descending values: `k` pairs from `2^band`,
/// dropping `2^288` inside each pair and one across pairs.
fn freeze_parade_values(k: usize) -> Vec<UBig> {
    let wide = UBig::ONE << 288usize;
    let mut values = Vec::with_capacity(2 * k);
    let mut v = UBig::ONE << (290 + bitlen(k));
    for _ in 0..k {
        values.push(v.clone());
        v -= &wide;
        values.push(v.clone());
        v -= UBig::ONE;
    }
    values
}

/// A min-lifted complete subtree's readable text spelling over a strictly
/// descending run: every node's minimum is its last leaf, so right children
/// print base 0 and left children the difference of the halves' minima.
fn min_lift_text(vals: &[UBig], parent_min: &UBig) -> String {
    if let [leaf] = vals {
        return (leaf - parent_min).to_string();
    }
    let my_min = vals.last().expect("nonempty");
    let (l, r) = vals.split_at(vals.len() / 2);
    format!(
        "({}, {}, {})",
        my_min - parent_min,
        min_lift_text(l, my_min),
        min_lift_text(r, my_min)
    )
}

