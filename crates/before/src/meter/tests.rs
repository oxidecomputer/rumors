//! Pins for the adversarial generators: each shape decodes, re-encodes
//! byte-identically, and has exactly its closed-form bit length.

use crate::{Party, Version};

use super::{bigroot, cliff_comb, dense, hugeleaf, id_spine, Packed};

/// Appended to the counter-comparison failures: the first cause to rule out
/// is a shared-process test runner, under which the process-global counters
/// bleed other tests' work into the reading being compared.
const ISOLATION_NOTE: &str = "note: the counter is process-global and meaningful only one \
     test per process: run under cargo nextest, not a shared-process cargo test";

/// Check an event-shape output: `decode` accepts it, the decoded version
/// re-encodes to the generated bytes (canonicality), and the live bit length
/// is exactly `bits`.
fn check_version(p: &Packed, bits: usize) {
    assert_eq!(p.bits, bits, "closed-form bit length");
    let v = Version::decode(&p.bytes[..]).expect("generated shape is strict normal form");
    assert_eq!(v.encoded_bits(), p.bits, "decoded live bit length");
    assert_eq!(v.encode(), p.bytes, "byte-identical re-encode");
}

/// Check an id-shape output: `decode` accepts it, the decoded party
/// re-encodes to the generated bytes (canonicality), and the live bit length
/// is exactly `bits`.
fn check_party(p: &Packed, bits: usize) -> Party {
    assert_eq!(p.bits, bits, "closed-form bit length");
    let id = Party::decode(&p.bytes[..]).expect("generated shape is strict normal form");
    assert_eq!(id.encoded_bits(), p.bits, "decoded live bit length");
    assert_eq!(id.encode(), p.bytes, "byte-identical re-encode");
    id
}

/// The dense spine `S(d)` is canonical normal form at exactly `4d + 4` bits,
/// at both a small and a large depth.
#[test]
fn dense_decodes_canonically_at_predicted_length() {
    for d in [3, 1000] {
        check_version(&dense(d), 4 * d + 4);
    }
}

/// `bigroot(b, d)` is canonical normal form at exactly `2b + 4d + 8` bits,
/// including a root magnitude wide enough to spill machine-word gamma
/// decoding.
#[test]
fn bigroot_decodes_canonically_at_predicted_length() {
    for (b, d) in [(3, 2), (100, 50)] {
        check_version(&bigroot(b, d), 2 * b + 4 * d + 8);
    }
}

/// `hugeleaf(b)` is canonical normal form at exactly `2b + 2` bits, including
/// a magnitude wide enough to spill machine-word gamma decoding.
#[test]
fn hugeleaf_decodes_canonically_at_predicted_length() {
    for b in [1, 200] {
        check_version(&hugeleaf(b), 2 * b + 2);
    }
}

/// `cliff_comb(k, n)` is canonical normal form at exactly `n(2k + 10) + 2`
/// bits, and its preorder leaf values oscillate across the `2^k` boundary.
///
/// The sizes cover a tooth magnitude wide enough to spill machine-word gamma
/// decoding and a tooth count deep enough for the oscillation to dominate.
#[test]
fn cliff_comb_decodes_canonically_at_predicted_length() {
    for (k, n) in [(2, 1), (3, 4), (200, 50)] {
        check_version(&cliff_comb(k, n), n * (2 * k + 10) + 2);
    }
    // The oscillation the family exists for: leaf values alternate
    // `2^k − 1 ↔ 2^k`, pinned on a hand-checkable size via the paper
    // notation (leaf values are absolute there).
    let p = cliff_comb(3, 2);
    let v = Version::decode(&p.bytes[..]).expect("comb is strict normal form");
    assert_eq!(v.to_string(), "(0, (7, 0, 1), (0, (7, 0, 1), 0))");
}

/// The stack-segment meter observes deep recursion, resets to zero, and reads
/// the same count for the same traversal repeated at the same call depth
/// (determinism is what makes it envelope-able).
///
/// The counter is process-global, so the repeat-run comparison is meaningful
/// under nextest's one-test-per-process isolation (this workspace's runner).
#[test]
fn stack_segment_meter_counts_deterministically_and_resets() {
    // Comparison recurses on depth; decode itself parses iteratively and
    // must not show up in the meter.
    let p = dense(50_000);
    let v = Version::decode(&p.bytes[..]).expect("dense spine decodes");
    super::reset_stack_segments();
    let first = {
        let _ = v.partial_cmp(&Version::new());
        super::stack_segments()
    };
    assert!(first > 0, "a depth-50000 comparison must grow the stack");
    super::reset_stack_segments();
    assert_eq!(
        super::stack_segments(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    let _ = v.partial_cmp(&Version::new());
    assert_eq!(
        super::stack_segments(),
        first,
        "identical traversals at identical call depth grow identical segments: {ISOLATION_NOTE}"
    );
}

/// The limb meter observes arithmetic width, resets to zero, and reads the
/// same count for the same operation repeated (determinism is what makes it
/// envelope-able); doubling a decoded magnitude grows the count.
///
/// The counter is process-global, so the repeat-run comparison is meaningful
/// under nextest's one-test-per-process isolation (this workspace's runner).
#[cfg(feature = "limb-meter")]
#[test]
fn limb_meter_counts_deterministically_and_resets() {
    // Wide-gamma decode is the arithmetic-width worst case: the whole input
    // is one code, so the decoded value's width is the input's bit length.
    let count_decode = |b: usize| {
        let p = hugeleaf(b);
        super::reset_limb_ops();
        let _ = Version::decode(&p.bytes[..]).expect("hugeleaf decodes");
        super::limb_ops()
    };
    let first = count_decode(10_000);
    assert!(first > 0, "a spilled-gamma decode must count limb work");
    super::reset_limb_ops();
    assert_eq!(
        super::limb_ops(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    assert_eq!(
        count_decode(10_000),
        first,
        "identical operations count identical limb work: {ISOLATION_NOTE}"
    );
    assert!(
        count_decode(20_000) > first,
        "a wider magnitude must count more limb work: {ISOLATION_NOTE}"
    );
}

/// `I(d, divert)` is canonical normal form at exactly `2d + 2` bits for both
/// divert arms, and the two arms own disjoint regions (the property that
/// drives two-operand id walks to full lockstep depth).
#[test]
fn id_spine_decodes_canonically_at_predicted_length() {
    for d in [1, 500] {
        let a = check_party(&id_spine(d, false), 2 * d + 2);
        let b = check_party(&id_spine(d, true), 2 * d + 2);
        assert!(a.is_disjoint(&b), "divert arms own disjoint regions");
    }
}
