/// The stack-segment meter observes deep guarded recursion, resets to
/// zero, counts deterministically, and reads zero over a deep fill walk.
///
/// Determinism — the same count for the same descent repeated at the same
/// call depth — is what makes the meter envelope-able; the deep fill reads
/// zero because its explicit stacks put depth on the heap instead.
///
/// Every library walk is iterative, so the meter's liveness needs its own
/// witness: a test-local descent routed through `recurse::descend!` (the
/// same guard the test-only oracle bridge walks use) deep enough to outrun
/// the thread stack. Without that leg, the boards' all-zero segments column
/// could be a dead counter instead of a measured fact.
///
/// The counter is process-global, so the repeat-run comparison is meaningful
/// under nextest's one-test-per-process isolation (this workspace's runner).
#[test]
fn stack_segment_meter_counts_deterministically_and_resets() {
    use crate::recurse::descend;
    /// A guarded descent to `floor`, each frame holding a small
    /// stack-resident payload so its size is honest.
    fn dive(depth: usize, floor: usize) -> u64 {
        if depth == floor {
            return 1;
        }
        let pad = [depth as u64; 8];
        let below = descend!(depth + 1, dive(depth + 1, floor));
        below + core::hint::black_box(pad)[0]
    }
    const FLOOR: usize = 200_000;
    super::reset_stack_segments();
    core::hint::black_box(dive(0, FLOOR));
    let first = super::stack_segments();
    assert!(
        first > 0,
        "a depth-200000 guarded descent must grow the stack"
    );
    super::reset_stack_segments();
    assert_eq!(
        super::stack_segments(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    core::hint::black_box(dive(0, FLOOR));
    assert_eq!(
        super::stack_segments(),
        first,
        "identical descents at identical call depth grow identical segments: {ISOLATION_NOTE}"
    );

    // The conversion ratchet: the fill walk pairs a deep spine on BOTH
    // sides — exactly the descent that once grew the stack — and must now
    // read zero, its depth on explicit heap stacks the heap meter prices.
    let v = dense(50_000).version();
    let id = Party::decode(&id_spine(50_000, false).bytes[..]).expect("id spine decodes");
    super::reset_stack_segments();
    let mut t = v.clone();
    t.tick(&id);
    assert_eq!(
        super::stack_segments(),
        0,
        "the iterative fill walk grows no stack segments: {ISOLATION_NOTE}"
    );
}

/// The limb meter observes arithmetic width, resets to zero, and reads the
/// same count for the same operation repeated (determinism is what makes it
/// envelope-able); doubling a decoded magnitude grows the count.
///
/// The counter is process-global, so the repeat-run comparison is meaningful
/// under nextest's one-test-per-process isolation (this workspace's runner).
#[cfg(feature = "limb-meter")]
#[test]
fn limb_meter_counts_deterministically_and_resets() {
    // Wide-gamma decode is the arithmetic-width worst case: the whole input
    // is one code, so the decoded value's width is the input's bit length.
    let count_decode = |b: usize| {
        let p = hugeleaf(b);
        super::reset_limb_ops();
        let _ = p.version();
        super::limb_ops()
    };
    let first = count_decode(10_000);
    assert!(first > 0, "a spilled-gamma decode must count limb work");
    super::reset_limb_ops();
    assert_eq!(
        super::limb_ops(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    assert_eq!(
        count_decode(10_000),
        first,
        "identical operations count identical limb work: {ISOLATION_NOTE}"
    );
    assert!(
        count_decode(20_000) > first,
        "a wider magnitude must count more limb work: {ISOLATION_NOTE}"
    );
}

/// The scan meter observes packed-stream traversal, resets to zero, and
/// reads the same count for the same operation repeated.
///
/// Determinism is what makes it envelope-able, and its floor is live — a
/// strict decode scans every live bit at least once — so a ceiling
/// asserted over it can never pass vacuously at zero.
///
/// The counter is process-global, so the repeat-run comparison is
/// meaningful under nextest's one-test-per-process isolation (this
/// workspace's runner).
#[cfg(feature = "scan-meter")]
#[test]
fn scan_meter_counts_deterministically_and_resets() {
    // A strict id decode reads each live bit exactly once through the
    // sequential cursor, so the count has both a floor and an exact
    // expectation.
    let count_decode = |d: usize| {
        let p = id_spine(d, false);
        super::reset_scan_bits();
        let _ = Party::decode(&p.bytes[..]).expect("id spine decodes");
        (super::scan_bits(), p.bits as u64)
    };
    let (first, bits) = count_decode(10_000);
    assert!(
        first >= bits,
        "a strict decode of {bits} live bits scanned only {first}: \
         the sequential cursor is not recording: {ISOLATION_NOTE}"
    );
    super::reset_scan_bits();
    assert_eq!(
        super::scan_bits(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    assert_eq!(
        count_decode(10_000).0,
        first,
        "identical operations scan identical bits: {ISOLATION_NOTE}"
    );
    assert!(
        count_decode(20_000).0 > first,
        "a longer stream must scan more bits: {ISOLATION_NOTE}"
    );

    // The write side is live too: joining two disjoint spines writes the
    // joined tree through the id builder, so the count covers reads of
    // both operands plus at least the output's own bits.
    let pa = id_spine(1_000, false);
    let pb = id_spine(1_000, true);
    let mut a = Party::decode(&pa.bytes[..]).expect("id spine decodes");
    let b = Party::decode(&pb.bytes[..]).expect("id spine decodes");
    super::reset_scan_bits();
    a.join(b).expect("the divert arms are disjoint");
    let joined = super::scan_bits();
    assert!(
        joined as usize >= a.encoded_bits(),
        "a join that wrote {} output bits recorded only {joined} scan bits: \
         the id builder is not recording its writes: {ISOLATION_NOTE}",
        a.encoded_bits(),
    );
}

