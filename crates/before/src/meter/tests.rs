//! Pins for the adversarial generators: each shape decodes, re-encodes
//! byte-identically, and has exactly its closed-form bit length.

use crate::{Party, Version};

use super::{
    alt_spine, bigroot, cancelling_chain, cliff_comb, cliff_fan, dense, hugeleaf, id_spine,
    scattered_id, wide_tooth_comb, Packed,
};

/// Appended to the counter-comparison failures: the first cause to rule out
/// is a shared-process test runner, under which the process-global counters
/// bleed other tests' work into the reading being compared.
const ISOLATION_NOTE: &str = "note: the counter is process-global and meaningful only one \
     test per process: run under cargo nextest, not a shared-process cargo test";

/// Check an event-shape output: `decode` accepts it, the decoded version
/// re-encodes to the generated bytes (canonicality), and the live bit length
/// is exactly `bits`.
fn check_version(p: &Packed, bits: usize) {
    assert_eq!(p.bits, bits, "closed-form bit length");
    let v = Version::decode(&p.bytes[..]).expect("generated shape is strict normal form");
    assert_eq!(v.encoded_bits(), p.bits, "decoded live bit length");
    assert_eq!(v.encode(), p.bytes, "byte-identical re-encode");
}

/// Check an id-shape output: `decode` accepts it, the decoded party
/// re-encodes to the generated bytes (canonicality), and the live bit length
/// is exactly `bits`.
fn check_party(p: &Packed, bits: usize) -> Party {
    assert_eq!(p.bits, bits, "closed-form bit length");
    let id = Party::decode(&p.bytes[..]).expect("generated shape is strict normal form");
    assert_eq!(id.encoded_bits(), p.bits, "decoded live bit length");
    assert_eq!(id.encode(), p.bytes, "byte-identical re-encode");
    id
}

/// The dense spine `S(d)` is canonical normal form at exactly `4d + 4` bits,
/// at both a small and a large depth.
#[test]
fn dense_decodes_canonically_at_predicted_length() {
    for d in [3, 1000] {
        check_version(&dense(d), 4 * d + 4);
    }
}

