/// The stack-segment meter observes deep recursion, resets to zero, and reads
/// the same count for the same traversal repeated at the same call depth
/// (determinism is what makes it envelope-able).
///
/// The counter is process-global, so the repeat-run comparison is meaningful
/// under nextest's one-test-per-process isolation (this workspace's runner).
#[test]
fn stack_segment_meter_counts_deterministically_and_resets() {
    // Comparison recurses on depth; decode itself parses iteratively and
    // must not show up in the meter.
    let p = dense(50_000);
    let v = Version::decode(&p.bytes[..]).expect("dense spine decodes");
    super::reset_stack_segments();
    let first = {
        let _ = v.partial_cmp(&Version::new());
        super::stack_segments()
    };
    assert!(first > 0, "a depth-50000 comparison must grow the stack");
    super::reset_stack_segments();
    assert_eq!(
        super::stack_segments(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    let _ = v.partial_cmp(&Version::new());
    assert_eq!(
        super::stack_segments(),
        first,
        "identical traversals at identical call depth grow identical segments: {ISOLATION_NOTE}"
    );
}

/// The limb meter observes arithmetic width, resets to zero, and reads the
/// same count for the same operation repeated (determinism is what makes it
/// envelope-able); doubling a decoded magnitude grows the count.
///
/// The counter is process-global, so the repeat-run comparison is meaningful
/// under nextest's one-test-per-process isolation (this workspace's runner).
#[cfg(feature = "limb-meter")]
#[test]
fn limb_meter_counts_deterministically_and_resets() {
    // Wide-gamma decode is the arithmetic-width worst case: the whole input
    // is one code, so the decoded value's width is the input's bit length.
    let count_decode = |b: usize| {
        let p = hugeleaf(b);
        super::reset_limb_ops();
        let _ = Version::decode(&p.bytes[..]).expect("hugeleaf decodes");
        super::limb_ops()
    };
    let first = count_decode(10_000);
    assert!(first > 0, "a spilled-gamma decode must count limb work");
    super::reset_limb_ops();
    assert_eq!(
        super::limb_ops(),
        0,
        "reset returns the meter to zero: {ISOLATION_NOTE}"
    );
    assert_eq!(
        count_decode(10_000),
        first,
        "identical operations count identical limb work: {ISOLATION_NOTE}"
    );
    assert!(
        count_decode(20_000) > first,
        "a wider magnitude must count more limb work: {ISOLATION_NOTE}"
    );
}

/// `I(d, divert)` is canonical normal form at exactly `2d + 2` bits for both
/// divert arms, and the two arms own disjoint regions (the property that
/// drives two-operand id walks to full lockstep depth).
#[test]
fn id_spine_decodes_canonically_at_predicted_length() {
    for d in [1, 500] {
        let a = check_party(&id_spine(d, false), 2 * d + 2);
        let b = check_party(&id_spine(d, true), 2 * d + 2);
        assert!(a.is_disjoint(&b), "divert arms own disjoint regions");
    }
}

/// `Z(e)` is canonical normal form at exactly `6e + 2` bits, and projecting
/// a comb through it keeps a wide magnitude per kept tooth: the projected
/// output out-scales the scattered party's own bits.
///
/// The overlap claim is what the generator exists for — the owned left
/// subtrees sit at the comb's tooth positions — so a projection that came
/// back near-empty would mean the shapes no longer align.
#[test]
fn scattered_id_decodes_canonically_at_predicted_length() {
    for e in [1, 500] {
        check_party(&scattered_id(e), 6 * e + 2);
    }
    let (k, n) = (64, 16);
    let comb = Version::decode(&cliff_comb(k, n).bytes[..]).expect("comb is strict normal form");
    let party =
        Party::decode(&scattered_id(n / 2).bytes[..]).expect("scattered id is strict normal form");
    let projected = &comb / &party;
    assert!(
        projected.encoded_bits() >= (n / 2) * k,
        "projection through the scattered id must keep a wide magnitude per kept tooth \
         (got {} bits from {} teeth of {} bits)",
        projected.encoded_bits(),
        n,
        k
    );
}
