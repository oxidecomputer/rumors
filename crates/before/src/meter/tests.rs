/// Appended to the counter-comparison failures: the first cause to rule out is
/// a shared-process test runner, under which the process-global counters bleed
/// other tests' work into the reading being compared.
const ISOLATION_NOTE: &str = "note: the counter is process-global and meaningful only one \
     test per process: run under cargo nextest, not a shared-process cargo test";

/// Check an event-shape output: the construction stream has exactly the
/// closed-form `bits`, and it lifts through the transcoding bridge into a
/// version that survives a wire round-trip (canonicality of both codings).
fn check_version(p: &Packed, bits: usize) {
    assert_eq!(p.bits, bits, "closed-form bit length");
    let v = p.version();
    let wire = v.encode();
    let back = Version::decode(&wire[..]).expect("a stored version's wire bytes decode");
    assert_eq!(back, v, "wire round-trip");
    assert_eq!(back.encode(), wire, "byte-identical re-encode");
}

/// Check an id-shape output: `decode` accepts it, the decoded party re-encodes
/// to the generated bytes (canonicality), and the live bit length is exactly
/// `bits`.
fn check_party(p: &Packed, bits: usize) -> Party {
    assert_eq!(p.bits, bits, "closed-form bit length");
    let id = Party::decode(&p.bytes[..]).expect("generated shape is strict normal form");
    assert_eq!(id.encoded_bits(), p.bits, "decoded live bit length");
    assert_eq!(id.encode(), p.bytes, "byte-identical re-encode");
    id
}

