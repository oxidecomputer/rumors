/// `Z(e)` is canonical normal form at exactly `6e + 2` bits, and projecting
/// a comb through it keeps a wide magnitude per kept tooth: the projected
/// output out-scales the scattered party's own bits.
///
/// The overlap claim is what the generator exists for — the owned left
/// subtrees sit at the comb's tooth positions — so a projection that came
/// back near-empty would mean the shapes no longer align.
#[test]
fn scattered_id_decodes_canonically_at_predicted_length() {
    for e in [1, 500] {
        check_party(&scattered_id(e), 6 * e + 2);
    }
    let (k, n) = (64, 16);
    let comb = cliff_comb(k, n).version();
    let party =
        Party::decode(&scattered_id(n / 2).bytes[..]).expect("scattered id is strict normal form");
    let projected = (&comb / &party).to_version();
    assert!(
        projected.encoded_bits() >= (n / 2) * k,
        "projection through the scattered id must keep a wide magnitude per kept tooth \
         (got {} bits from {} teeth of {} bits)",
        projected.encoded_bits(),
        n,
        k
    );
}

/// `MT(k, n)` is three canonical operands at their closed-form lengths,
/// and the correlation realizes the full-walk verdict: the projected comb
/// sits strictly under the plateau, fused and materialized alike.
///
/// The `Less` verdict is what keeps every measurement of this family a
/// whole-overlay walk (no early exit), so a generator drift that broke
/// the alignment would read here as a changed verdict.
#[test]
fn mask_drift_triple_decodes_canonically_and_realizes_less() {
    let (k, n) = (64, 16);
    let (comb, mask, plateau) = mask_drift_triple(k, n);
    check_version(&comb, n * (2 * k + 10) + 2);
    check_version(&plateau, 2 * k + 2);
    let party = check_party(&mask, 6 * (n / 2) + 2);
    let (v, w) = (comb.version(), plateau.version());
    let fused = (&v / &party).partial_cmp(&w);
    assert_eq!(
        fused,
        Some(std::cmp::Ordering::Less),
        "the projected comb sits strictly under the plateau"
    );
    assert_eq!(
        fused,
        (&v / &party).to_version().partial_cmp(&w),
        "the fused verdict is the materialized verdict"
    );
}

/// `MQ(k, n)` is two canonical comb/mask pairs whose interleaved
/// parities realize the full-walk `Less` verdict.
///
/// Both operand pairs decode canonically at their closed-form lengths,
/// the sparse comb's view is semantically empty (its mask owns exactly
/// its zero levels), and the fused four-stream verdict matches the
/// materialized comparison.
#[test]
fn mask_drift_quadruple_decodes_canonically_and_realizes_less() {
    let (k, n) = (64, 16);
    let ((sparse, even_mask), (comb, odd_mask)) = mask_drift_quadruple(k, n);
    check_version(&sparse, (n / 2) * (2 * k + 14) + 2);
    check_version(&comb, n * (2 * k + 10) + 2);
    let p1 = check_party(&even_mask, 6 * (n / 2) + 2);
    let p2 = check_party(&odd_mask, 6 * (n / 2) + 4);
    let (v1, v2) = (sparse.version(), comb.version());
    assert!(
        (&v1 / &p1).to_version().is_empty(),
        "the even mask owns exactly the sparse comb's zero levels"
    );
    assert!(
        !(&v2 / &p2).to_version().is_empty(),
        "the odd mask keeps the full comb's teeth"
    );
    let fused = (&v1 / &p1).partial_cmp(&(&v2 / &p2));
    assert_eq!(
        fused,
        Some(std::cmp::Ordering::Less),
        "the empty view sits strictly under the tooth-keeping view"
    );
    assert_eq!(
        fused,
        (&v1 / &p1)
            .to_version()
            .partial_cmp(&(&v2 / &p2).to_version()),
        "the fused verdict is the materialized verdict"
    );
}

/// The leaf count of a stored version's skyline stream, by one iterative
/// topology walk (payload codes skipped unread).
fn leaf_count(v: &Version) -> usize {
    use codec::BitCursor;
    let all = codec::bytes_as_bits(v.as_bytes());
    let bits = &all[..v.encoded_bits()];
    let mut cur = codec::DsiCursor::new(bits);
    let mut pending = 1usize;
    let mut leaves = 0usize;
    while pending > 0 {
        pending -= 1;
        if cur.read_bit().expect("a stored stream is canonical") {
            cur.skip_int().expect("a stored stream is canonical");
            leaves += 1;
        } else {
            pending += 2;
        }
    }
    leaves
}

/// `JP(k, m, d)` is canonical normal form at its closed-form bit
/// lengths, and its overlays realize the interleave the family exists
/// for.
///
/// The lengths: exactly `132d + m(2k + 14) + 2` bits (teeth) and
/// `132d + 14m + 2k + 2` bits (band). The overlays: the meet keeps both
/// band leaves per tooth and both gap leaves per level (4 leaves per
/// comb level — a cheap code one fold behind every wide difference
/// crest), while the join collapses every comb level to its two
/// plateaus (the band shades every gap): the wide crests live in the
/// meet-side overlay alone.
#[test]
fn jump_pair_decodes_canonically_at_predicted_lengths_and_interleaves() {
    for (k, m, d) in [(3, 1, 1), (400, 8, 2)] {
        let (a, b) = jump_pair(k, m, d);
        check_version(&a, 132 * d + m * (2 * k + 14) + 2);
        check_version(&b, 132 * d + 14 * m + 2 * k + 2);
        let (a, b) = (a.version(), b.version());
        let spine_leaves = super::JUMP_PAIR_DIGIT_STRIDE * d;
        assert_eq!(
            leaf_count(&(&a & &b)),
            spine_leaves + 4 * m + 1,
            "the meet must keep the band and gap interleave whole"
        );
        assert_eq!(
            leaf_count(&(&a | &b)),
            spine_leaves + 2 * m + 1,
            "the join must collapse each comb level to its two plateaus"
        );
        // The valuation identity, on the public surface: the pair's
        // distance is its two lags' sum (rank modularity).
        let d1 = a.lag(&b);
        let d2 = b.lag(&a);
        assert_eq!(a.distance(&b), &d1 + &d2, "distance is the lags' sum");
    }
}

/// `CP(n)` builds two genuinely concurrent organic versions that switch
/// sides at every overlay boundary.
///
/// The join and the meet both keep one plateau per forked leaf — every
/// one of the `n − 1` overlay boundaries a side switch — and the
/// distance is the integer rank 2 at every `n` (each leaf's dominant
/// and dominated heights differ by exactly 2, so the schedule's heights
/// are realized end to end).
#[test]
fn concurrent_pair_alternates_dominance_at_every_boundary() {
    for n in [4, 64] {
        let (v, w) = concurrent_pair(n);
        assert!(v.concurrent(&w), "the pair must be causally concurrent");
        assert_eq!(
            leaf_count(&(&v | &w)),
            n,
            "the join must keep one plateau per forked leaf"
        );
        assert_eq!(
            leaf_count(&(&v & &w)),
            n,
            "the meet must keep one plateau per forked leaf"
        );
        let two = Version::try_from(2u64)
            .expect("a small integer version is valid")
            .rank();
        assert_eq!(v.distance(&w), two, "the schedule's heights are realized");
    }
}
