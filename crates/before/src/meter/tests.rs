/// `plateau_puncture(w, d)` is canonical normal form at exactly `d(64w + 262) +
/// 4` bits.
///
/// The length derivation: `66d` spine levels at 2 bits, `d` turn leaves at
/// `64w` bits each (the plateau's exact `32w`-bit width, bit 0 clear, keeps its
/// gamma code at `2 · 32w` with the leaf flag), the bottom 1 leaf at 4 bits,
/// and `65d` trailing 0-leaves at 2 bits. Its `min_ticks` is exactly the
/// stored-base sum `d · x + 1` (the turn leaves all on the plateau plus the
/// bottom 1), and its exact rank realizes the answer-embedded product the
/// family exists for: `rank · 2^(66d) = 2 · x · y + 1` over the committed
/// factors, checked here through the public fold at hand-checkable sizes (the
/// `answer_embedded_product` pin in `tests/meter.rs` measures the cost at meter
/// scale; the query fold's differential suite pins the value against the
/// oracle, and its proptest pins the same embedding over arbitrary factors).
#[test]
fn plateau_puncture_decodes_canonically_at_predicted_length() {
    for (w, d) in [(10usize, 1usize), (12, 5), (40, 40)] {
        check_version(&plateau_puncture(w, d), d * (64 * w + 262) + 4);
        // The reduction's size premise, exact on the committed instance: the
        // STORED stream is `128w + 198d + 2` bits — `4·bits(x) + 3·bits(2y) +
        // 5`, the climb and plunge codes at `2·bits(x)` each plus 3 bits per
        // level — linear in the factors' widths even though the packed
        // construction above is `Θ(d·w)` (it spells the plateau per turn). The
        // floor's funding argument divides the fold's cost by exactly this
        // stored size, so the premise is pinned beside the length it must not
        // drift from (the arbitrary-factor proptest beside the query fold pins
        // the same bound as an inequality).
        assert_eq!(
            plateau_puncture(w, d).version().encoded_bits(),
            128 * w + 198 * d + 2,
            "the stored stream must stay linear in the factors' widths"
        );
        let (x, y) = plateau_puncture_factors(w, d);
        let expected = UBig::from(d as u64) * &x + 1u8;
        let ticks: crate::Ticks = expected
            .to_string()
            .parse()
            .expect("the closed form renders as a count");
        assert_eq!(
            plateau_puncture(w, d).version().min_ticks(),
            ticks,
            "the stored-base sum is the family's minimum tick count"
        );
        // The answer-embedded product, through the public fold: the rank is
        // exactly (2xy + 1) / 2^(66d), and the numerator is odd, so the
        // rendered rational is already in lowest terms.
        let numerator = ((&x * &y) << 1usize) + 1u8;
        assert_eq!(
            plateau_puncture(w, d).version().rank().to_string(),
            format!("{numerator}/2^{}", 66 * d),
            "the exact rank is the plateau times the punctured turn mass"
        );
    }
}

/// `arming_train(n, w, g, alternate)` is canonical normal form at exactly
/// `n(g(2·band + 132) + 8·band + 16) + 2` bits, `band = 32w + ⌈log₂ n⌉ + 2`.
///
/// Its `min_ticks` is the mirrored leaf-value sum (the recurrence the generator
/// doc states): the swing, park, kicker, and promoting-freeze leaves per block
/// plus `g` plateau turns per window, over the bottom 0. The same-sign and
/// alternating trains share topology and differ only in the swings' directions.
#[test]
fn arming_train_decodes_canonically_at_predicted_length() {
    for (n, w, g, alt) in [
        (1usize, 19usize, 1usize, false),
        (2, 19, 1, true),
        (3, 20, 2, true),
        (4, 19, 3, false),
    ] {
        let band = 32 * w + (usize::BITS - n.leading_zeros()) as usize + 2;
        check_version(
            &arming_train(n, w, g, alt),
            n * (g * (2 * band + 132) + 8 * band + 16) + 2,
        );
        // The mirror: replay the generator's plateau recurrence and sum every
        // leaf value (the bottom and trailing leaves are all 0).
        let arm = UBig::ONE << (32 * w);
        let kicker = UBig::ONE << 288usize;
        let mut plateau = (UBig::ONE << band) + (&arm << 1);
        let mut expected = UBig::ZERO;
        for b in 0..n {
            expected += &plateau * UBig::from(g as u64); // the window turns
            if alt && b % 2 == 1 {
                plateau -= &arm;
            } else {
                plateau += &arm;
            }
            for kick in [UBig::ZERO, UBig::ONE, kicker.clone(), UBig::ONE] {
                plateau += kick;
                expected += &plateau;
            }
        }
        let ticks: crate::Ticks = expected
            .to_string()
            .parse()
            .expect("the mirrored sum renders as a count");
        assert_eq!(
            arming_train(n, w, g, alt).version().min_ticks(),
            ticks,
            "the mirrored leaf-value sum is the family's minimum tick count"
        );
    }
}

/// The dense-suffix families' readable text spelling: the 33-stride
/// gap spine over `p` re-arm blocks with the arming climb `2^arm_bits`.
fn dense_suffix_text(p: usize, d: usize, arm_bits: usize) -> String {
    let arm = (UBig::ONE << arm_bits).to_string();
    let settle = (UBig::ONE << 288usize).to_string();
    let mut text = String::new();
    for t in 1..=33 * d {
        if t % 33 == 1 {
            text.push_str("(0, 1, ");
        } else {
            text.push_str("(0, ");
        }
    }
    for _ in 0..p {
        text.push('(');
        text.push_str(&arm);
        text.push_str(", 0, (1, 0, (");
        text.push_str(&settle);
        text.push_str(", 0, (1, 0, ");
    }
    text.push('1');
    for _ in 0..4 * p {
        text.push(')');
    }
    for t in (1..=33 * d).rev() {
        if t % 33 == 1 {
            text.push(')');
        } else {
            text.push_str(", 0)");
        }
    }
    text
}

/// The weight-comb and freeze-parade families' readable text spelling: the
/// parked-unit spine at depth `s` over one block as the root's right child.
fn parked_spine_text(s: usize, block: &str) -> String {
    let mut text = String::new();
    text.push_str("(0, ");
    for _ in 1..s - 1 {
        text.push_str("(0, ");
    }
    text.push_str("(0, 1, 0)");
    for _ in 1..s - 1 {
        text.push_str(", 1)");
    }
    text.push_str(", ");
    text.push_str(block);
    text.push(')');
    text
}

