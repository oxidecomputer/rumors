/// `promotion_rearm(p)` is canonical normal form at exactly `1972p + 4` bits.
///
/// Its `min_ticks` is exactly the stored-base sum `16p + p(2^608 + 2^288 + 2) +
/// 1`, and the built tree is exactly the nested text form the family reasons
/// about.
///
/// The closed form is the family's independent semantic leg: the
/// `skyline_flatness` bands in `tests/meter.rs` re-derive it at meter scale, so
/// this pin holds it at hand-checkable sizes, and the text comparison pins the
/// bit-level construction against the readable spelling (the 1, 0, 1, 0, …
/// span-builder, then `2^608, 1, 2^288, 1` blocks over the terminal 1).
#[test]
fn promotion_rearm_decodes_canonically_at_predicted_length() {
    for p in [1usize, 5, 200] {
        check_version(&promotion_rearm(p), 1972 * p + 4);
        let expected = UBig::from(16 * p as u64)
            + UBig::from(p as u64) * ((UBig::ONE << 608usize) + (UBig::ONE << 288usize) + 2u8)
            + 1u8;
        let ticks: crate::Ticks = expected
            .to_string()
            .parse()
            .expect("the closed form renders as a count");
        assert_eq!(
            promotion_rearm(p).version().min_ticks(),
            ticks,
            "the stored-base sum is the family's minimum tick count"
        );
    }
    let p = 2;
    let arm = (UBig::ONE << 608usize).to_string();
    let settle = (UBig::ONE << 288usize).to_string();
    let mut text = String::new();
    let mut nodes = 0usize;
    for level in 0..32 * p {
        text.push_str(if level % 2 == 0 { "(0, 1, " } else { "(0, 0, " });
        nodes += 1;
    }
    for _ in 0..p {
        text.push('(');
        text.push_str(&arm);
        text.push_str(", 0, (1, 0, (");
        text.push_str(&settle);
        text.push_str(", 0, (1, 0, ");
        nodes += 4;
    }
    text.push('1');
    for _ in 0..nodes {
        text.push(')');
    }
    let spelled: Version = text.parse().expect("the spelled spine is canonical");
    assert_eq!(
        promotion_rearm(p).version(),
        spelled,
        "the bit-level construction is the spelled re-arm spine"
    );
}

